def write(api: Api, root: Path, prefix: str) -> list[Path]:
    out = root / "python" / "src" / "bytnode" / "_generated"
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "__init__.py": HEADER + '"""Code generated from the public OpenAPI contract."""\n',
        "literals.py": emit_literals(api),
        "models.py": emit_models(api, prefix),
        "snapshot.py": emit_snapshot(api),
        "indicators_result.py": emit_indicators_result(),
        "indicators.py": emit_indicators(api),
        "resources.py": emit_resources(api, sync=True),
        "async_resources.py": emit_resources(api, sync=False),
        "routes.py": emit_routes(api),
    }
    written = []
    for name, content in files.items():
        p = out / name
        p.write_text(content, encoding="utf-8", newline="\n")
        written.append(p)
