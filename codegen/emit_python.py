def emit_snapshot(api: Api) -> str:
    lines = [
        HEADER,
        '"""The payload of `GET /v1/snapshot`: one attribute per requested field."""',
        "",
        "from __future__ import annotations",
        "",
        "from pydantic import Field as PydField",
        "",
        "from .._models_base import BytnodeModel",
        "from . import models as m",
        "",
        "",
        "class SnapshotData(BytnodeModel):",
        '    """The fields you asked for, each typed like the route that serves the same content.',
        "",
        "    A multi-timeframe field is read as `klines_1h` (or `data[\"klines@1h\"]`). A field",
        "    is `None` when it was not requested, is out of your plan, or has no data: the",
        "    response's `unavailable` / `out_of_plan_fields` say which.",
        '    """',
        "",
    ]
    for f in api.snapshot_fields:
        attr = py_ident(f.wire.replace("@", "_"))
        # A field limited to depth 1 is its route's OBJECT (or None), never a list.
        if f.model and f.maximum == 1:
            t = f"m.{f.model} | None"
        else:
            t = f"m.{f.model} | list[m.{f.model}] | None" if f.model else "object | None"
        lines.append(f"    {attr}: {t} = PydField(None, alias={f.wire!r}, description={f.description[:300]!r})")
    lines.append("")
    lines.append("")
    lines.append("SNAPSHOT_FIELDS: dict[str, tuple[str, str | None]] = {")
    for f in api.snapshot_fields:
        lines.append(f"    {f.wire!r}: ({f.base!r}, {f.timeframe!r}),")
    lines.append("}")
    lines.append('"""Every snapshot field: wire name -> (base name, timeframe)."""')
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- resources


def class_name(node: Node, sync: bool) -> str:
    base = "".join(pascal(s) for s in node.path) or "Root"
    return ("" if sync else "Async") + base + "Resource"


def call_params(r: Route) -> list[Param]:
    """Parameters of the method, in signature order: required first, then optional."""
    req = [p for p in r.params if p.required]
    opt = [p for p in r.params if not p.required]
    order = {"symbol": 0, "asset": 1, "series": 2, "timeframe": 3, "expiry": 4}
    req.sort(key=lambda p: (p.location != "path", order.get(p.name, 9)))
    later = {"limit": 0, "since": 1, "until": 2, "before": 3, "order": 4, "after_id": 5, "fields": 99}
    opt.sort(key=lambda p: later.get(p.name, 50))
    return req + opt


def param_type(p: Param) -> str:
    if p.time:
        return "TimeLike"
    if p.wire == "fields":
        return "Fields"
    return type_py(p.type)


def signature(params: list[Param], extra: list[str]) -> list[str]:
    out = ["        self,"]
    star = False
    for p in params:
        if not p.required and not star:
            out.append("        *,")
            star = True
        name = p.name if p.name not in RESERVED else p.name + "_"
        if p.required:
            out.append(f"        {name}: {param_type(p)},")
        else:
            out.append(f"        {name}: {param_type(p)} | None = None,")
    if not star:
        out.append("        *,")
    out.extend(f"        {e}," for e in extra)
    return out


def args_doc(params: list[Param], extra_doc: dict[str, str]) -> list[str]:
    lines = ["", "        Args:"]
    for p in params:
        name = p.name if p.name not in RESERVED else p.name + "_"
        desc = p.description
        if p.time:
            desc = TIME_DOC[p.wire] + " A `datetime` (naive = UTC), a `date`, an ISO string (`2026-01-01`, `2026-01-01T12:00:00Z`) or epoch milliseconds."
        if p.wire == "fields":
            desc = "Only return these fields of each row (a list or a comma-separated string; dotted paths reach nested keys). Rows are then partial and not validated."
        if p.default is not None and "default" not in desc.lower():
            desc += f" Default: `{p.default}`."
        lines.extend(arg_lines(name, desc))
    for k, v in extra_doc.items():
        lines.extend(arg_lines(k, v))
    return lines


def arg_lines(name: str, desc: str) -> list[str]:
    """One Google-style `Args:` entry: continuation lines indented under the name."""
    text = " ".join(desc.split())
    return textwrap.wrap(
        f"{name}: {text}", 92, initial_indent=" " * 12, subsequent_indent=" " * 16, break_long_words=False, break_on_hyphens=False
    )


def params_dict(params: list[Param]) -> str:
    items = []
    for p in params:
        name = p.name if p.name not in RESERVED else p.name + "_"
        items.append(f"{p.wire!r}: {name}")
    return "{" + ", ".join(items) + "}"


def return_type(r: Route) -> str:
    if r.shape == "list":
        return f"Response[list[m.{r.model}]]" if r.model else "Response[list[Any]]"
    if r.shape == "object":
        return f"Response[m.{r.model} | None]" if r.model else "Response[Any]"
    return "Response[Any]"


def route_spec(r: Route) -> str:
    limit = next((p for p in r.params if p.wire == "limit"), None)
    path_params = tuple(p.wire for p in r.params if p.location == "path")
    return (
        f"RouteSpec(path={r.path!r}, method={r.method!r}, shape={r.shape!r}, "
        f"model={'m.' + r.model if r.model else None}, paginated={r.paginated!r}, "
        f"path_params={path_params!r}, max_limit={int(limit.maximum) if limit and limit.maximum else None!r}, "
        f"range_mode={'after_id' in {p.wire for p in r.params}!r})"
    )


def emit_route_methods(r: Route, sync: bool) -> list[str]:
    aw = "" if sync else "await "
    df = "def" if sync else "async def"
    params = call_params(r)
    title = f"{r.method} {r.path}"
    lines = [f"    _route = {route_spec(r)}", ""]
    lines.append(f"    {df} __call__(")
    lines.extend(signature(params, ["request_options: RequestOptions | None = None"]))
    lines.append(f"    ) -> {return_type(r)}:")
    body = [f"{title} — {r.summary}", "", r.description]
    lines.append('        """' + esc(body[0]))
    lines.extend(esc(x) for x in doc("\n".join(body[1:]), 8))
    lines.extend(esc(x) for x in args_doc(params, {"request_options": "Per-request `timeout`, `max_retries` or extra `headers`."}))
    lines.append('        """')
    lines.append(f"        return {aw}self._call(self._route, {params_dict(params)}, request_options)")
    if r.paginated:
        iter_params = [p for p in params if p.wire not in ("limit", "before_ms", "after_id")]
        it = "RowIterator" if sync else "AsyncRowIterator"
        lines.append("")
        lines.append("    def iter(")
        lines.extend(
            signature(
                iter_params,
                ["page_size: int | None = None", "max_items: int | None = None", "request_options: RequestOptions | None = None"],
            )
        )
        lines.append(f"    ) -> {it}[m.{r.model}]:" if r.model else f"    ) -> {it}[Any]:")
        lines.append(f'        """Every row of `{r.path}` over a period, following `next` page after page.')
        lines.append("")
        lines.append("        Pages are fetched lazily, `page_size` rows at a time (default with `since`: the")
        lines.append("        route's maximum; without it, the route's default page, which stops at your plan's")
        lines.append("        history window). With `since`, rows come oldest first unless")
        lines.append("        `order` says otherwise. Call `.to_pandas()` / `.to_list()` to collect them.")
        lines.extend(
            esc(x)
            for x in args_doc(
                iter_params,
                {
                    "page_size": "Rows per request (`limit`), up to the route's maximum.",
                    "max_items": "Stop after this many rows.",
                    "request_options": "Per-request `timeout`, `max_retries` or extra `headers`.",
                },
            )
        )
        lines.append('        """')
        lines.append(
            f"        return self._iter(self._route, {params_dict(iter_params)}, page_size=page_size, max_items=max_items, request_options=request_options)"
        )
    return lines


def emit_snapshot_methods(api: Api, r: Route, sync: bool) -> list[str]:
    aw = "" if sync else "await "
    df = "def" if sync else "async def"
    singles = [f for f in api.snapshot_fields if not f.timeframe]
    multis: dict[str, list[str]] = {}
    for f in api.snapshot_fields:
        if f.timeframe:
            multis.setdefault(f.base, []).append(f.timeframe)
    lines = [f"    _route = {route_spec(r)}", ""]
    lines.append(f"    {df} __call__(")
    lines.append("        self,")
    lines.append("        symbol: str,")
    lines.append("        *,")
    for f in singles:
        # Depth 1 only: `True` (or 1), never a list.
        profondeur = "Literal[True, 1]" if f.maximum == 1 else "Depth"
        lines.append(f"        {py_ident(f.base)}: {profondeur} | None = None,")
    for base, tfs in multis.items():
        lit = "KlineTimeframe" if "1w" in tfs else "Timeframe"
        lines.append(f"        {base}: Mapping[{lit}, Depth] | None = None,")
    lines.append("        request_options: RequestOptions | None = None,")
    lines.append("    ) -> Response[SnapshotData]:")
    lines.append(f'        """GET /v1/snapshot — {esc(r.summary)}')
    lines.append("")
    lines.extend(esc(x) for x in doc(r.description, 8))
    lines.append("")
    lines.append("        Each field takes a depth: `True` for the latest value, or `N` for the N latest rows.")
    lines.append("        Multi-timeframe fields take a mapping: `klines={\"1h\": 24, \"1d\": 7}`.")
    lines.append("")
    lines.append("        Example:")
    lines.append('            snap = client.snapshot("BTCUSDT", funding_rate=True, basis=5, klines={"1h": 24})')
    lines.append("            snap.data.funding_rate.rate_pct")
    lines.append("            snap.data.klines_1h[0].close")
    lines.append('        """')
    lines.append("        fields: dict[str, Depth | None] = {")
    for f in singles:
        lines.append(f"            {f.wire!r}: {py_ident(f.base)},")
    lines.append("        }")
    for base in multis:
        lines.append(f"        for {base}_tf, {base}_depth in ({base} or {{}}).items():")
        lines.append(f'            fields[f"{base}@{{{base}_tf}}"] = {base}_depth')
    lines.append(f"        return {aw}self._snapshot(self._route, symbol, fields, request_options)")
    lines.append("")
    lines.append(f"    {df} catalog(self, symbol: str, *, request_options: RequestOptions | None = None) -> Response[Any]:")
    lines.append('        """The fields `snapshot()` accepts for `symbol`, their timeframes and maximum depths.')
    lines.append("")
    lines.append("        Read them in `response.meta`: `available_fields`, `available_multi_tf_fields`,")
    lines.append("        `timeframes_by_field`, `max_depth`.")
    lines.append('        """')
    lines.append(f"        return {aw}self._catalog(self._route, symbol, request_options)")
    return lines


def emit_indicator_methods(r: Route, sync: bool) -> list[str]:
    aw = "" if sync else "await "
    df = "def" if sync else "async def"
    return [
        f"    _route = {route_spec(r)}",
        "",
        f"    {df} __call__(",
        "        self,",
        "        symbol: str,",
        "        timeframe: KlineTimeframe,",
        "        indicators: Sequence[IndicatorSpec | Mapping[str, Any]],",
        "        *,",
        "        results: int | None = None,",
        "        request_options: RequestOptions | None = None,",
        "    ) -> Response[IndicatorsResult | None]:",
        f'        """POST /v1/indicators — {esc(r.summary)}',
        "",
        *[esc(x) for x in doc(r.description, 8)],
        "",
        "        Build the indicator list with `bytnode.indicators` (typed, checked locally):",
        "",
        "            from bytnode import indicators as ind",
        '            res = client.indicators("BTCUSDT", "1h", [ind.rsi(14), ind.macd(), ind.bb(20, std=2.5)], results=50)',
        '            res.data.indicators["rsi_14"].values',
        "            res.to_pandas()  # one column per output, indexed by candle time",
        "",
        "        Args:",
        "            symbol: Trading pair, e.g. `BTCUSDT`.",
        "            timeframe: Candle size, `1m` to `1w`.",
        "            indicators: Up to 50 specs, from `bytnode.indicators` or plain dicts",
        '                (`{"type": "rsi", "period": 14}`). Ids are generated when missing.',
        "            results: Values per indicator, 1 to 1000 (default 1).",
        "            request_options: Per-request `timeout`, `max_retries` or extra `headers`.",
        '        """',
        f"        return {aw}self._indicators(self._route, symbol, timeframe, indicators, results, request_options)",
    ]


def emit_node(api: Api, node: Node, sync: bool, out: list[str]) -> None:
    for child in node.children.values():
        emit_node(api, child, sync, out)
    if not node.path:
        return
    base = "SyncResource" if sync else "AsyncResource"
    out.append(f"class {class_name(node, sync)}({base}):")
    title = node.route.path if node.route else "/v1/" + "/".join(node.path)
    out.append(f'    """`{title}`{" and its sub-routes" if node.children else ""}."""')
    out.append("")
    for name, child in node.children.items():
        out.append(f"    {name}: {class_name(child, sync)}")
    if node.children:
        out.append("")
        out.append("    def __init__(self, client: Any) -> None:")
        out.append("        super().__init__(client)")
        for name, child in node.children.items():
            out.append(f"        self.{name} = {class_name(child, sync)}(client)")
        out.append("")
    r = node.route
    if r is not None:
        if r.shape == "snapshot":
            out.extend(emit_snapshot_methods(api, r, sync))
        elif r.shape == "indicators":
            out.extend(emit_indicator_methods(r, sync))
        else:
            out.extend(emit_route_methods(r, sync))
    elif not node.children:
        out.append("    pass")
    out.append("")
    out.append("")


def emit_resources(api: Api, sync: bool) -> str:
    base = "SyncResource" if sync else "AsyncResource"
    it = "RowIterator" if sync else "AsyncRowIterator"
    lines = [
        HEADER,
        f'"""{"Synchronous" if sync else "Asynchronous"} resources: one class per path segment of the API."""',
        "",
        "from __future__ import annotations",
        "",
        "from collections.abc import Mapping, Sequence",
        "from typing import Any, Literal",
        "",
        f"from .._resource import {base}",
        f"from .._response import {it}, Response",
        "from .._routes import RouteSpec",
        "from .._types import Depth, Fields, RequestOptions, TimeLike",
        "from .._indicator_spec import IndicatorSpec",
        "from . import models as m",
        "from .indicators_result import IndicatorsResult",
        f"from .literals import {', '.join(param_literals(api))}",
        "from .snapshot import SnapshotData",
        "",
        "",
    ]
    emit_node(api, api.tree, sync, lines)
    root = "Resources" if sync else "AsyncResources"
    lines.append(f"class {root}:")
    lines.append(f'    """Every route of the API, as attributes of the client (`client.{next(iter(api.tree.children))}`, ...)."""')
    lines.append("")
    for name, child in api.tree.children.items():
        lines.append(f"    {name}: {class_name(child, sync)}")
    lines.append("")
    lines.append("    def _init_resources(self) -> None:")
    for name, child in api.tree.children.items():
        lines.append(f"        self.{name} = {class_name(child, sync)}(self)")
    lines.append("")
    return "\n".join(lines) + "\n"


