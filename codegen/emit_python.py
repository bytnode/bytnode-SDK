"""Write the generated part of the Python SDK (`python/src/bytnode/_generated/`)."""

from __future__ import annotations

import keyword
import re
import textwrap
from pathlib import Path

from model import Api, Field, Model, Node, Param, Route, TypeRef, param_literals, pascal


def py_ident(name: str) -> str:
    """A Python-safe identifier for a wire name: `global` (a keyword) is `global_market`, like the resource."""
    if name == "global":
        return "global_market"
    return name + "_" if keyword.iskeyword(name) else name

HEADER = '''# This file is generated by codegen/generate.py from spec/openapi.json.
# Do not edit it by hand: change the generator or the overrides, then run `make generate`.
'''

TIME_DOC = {
    "since_ms": "Lower time bound, inclusive.",
    "until_ms": "Upper time bound, inclusive to the millisecond.",
    "before_ms": "Upper time bound, exclusive (rows strictly before it). Not combinable with `until`.",
}

RESERVED = set(keyword.kwlist) | {"self", "options", "request_options", "model_config", "model_fields"}


# --------------------------------------------------------------------------- helpers


def py_attr(name: str, prefix: str) -> str:
    """A valid Python attribute for a wire key (`30d` -> `last_30d`)."""
    attr = re.sub(r"\W", "_", name)
    if attr[:1].isdigit():
        attr = prefix + attr
    if attr in RESERVED or attr.startswith("model_"):
        attr = attr + "_"
    return attr


def doc(text: str, indent: int, width: int = 92) -> list[str]:
    """Wrap a markdown-ish text into docstring lines."""
    out: list[str] = []
    pad = " " * indent
    for para in text.replace("\r", "").split("\n"):
        para = para.rstrip()
        if not para:
            out.append("")
            continue
        bullet = re.match(r"^(\s*[-*]\s+)", para)
        sub = " " * len(bullet.group(1)) if bullet else ""
        lines = textwrap.wrap(para, width - indent, subsequent_indent=sub, break_long_words=False, break_on_hyphens=False)
        out.extend(pad + ln for ln in lines)
    while out and not out[-1]:
        out.pop()
    return out


def esc(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')


def type_py(t: TypeRef, *, model_prefix: str = "") -> str:
    if t.kind == "str":
        s = "str"
    elif t.kind == "int":
        s = "int"
    elif t.kind == "float":
        s = "float"
    elif t.kind == "bool":
        s = "bool"
    elif t.kind == "datetime":
        s = "datetime"
    elif t.kind == "date":
        s = "date"
    elif t.kind == "literal":
        s = t.name if t.name else "Literal[" + ", ".join(repr(v) for v in t.values) + "]"
    elif t.kind == "model":
        s = model_prefix + (t.name or "Any")
    elif t.kind == "list":
        s = f"list[{type_py(t.item, model_prefix=model_prefix) if t.item else 'Any'}]"
    elif t.kind == "dict":
        s = "dict[str, Any]"
    elif t.kind == "union":
        s = " | ".join(type_py(o, model_prefix=model_prefix) for o in t.options)
    else:
        return "Any"
    return f"{s} | None" if t.nullable else s


# --------------------------------------------------------------------------- literals


def emit_literals(api: Api) -> str:
    lines = [HEADER, '"""Closed sets of values accepted by the API."""', "", "from __future__ import annotations", "", "from typing import Literal", ""]
    names = []
    for lit in api.literals.values():
        names.append(lit.name)
        lines.append(f"{lit.name} = Literal[{', '.join(repr(v) for v in lit.values)}]")
        lines.append(f'"""{esc(lit.description)}"""')
        lines.append("")
    types = sorted({k for i in api.indicators for k in [i]})
    lines.append(f"IndicatorType = Literal[{', '.join(repr(t) for t in types)}]")
    lines.append('"""The technical indicators served by `POST /v1/indicators`."""')
    lines.append("")
    lines.append(f"ErrorCode = Literal[{', '.join(repr(c) for c in api.error_codes)}]")
    lines.append('"""Stable machine-readable `error.code` values. Branch on them, never on the message."""')
    lines.append("")
    names += ["IndicatorType", "ErrorCode"]
    lines.append("__all__ = [" + ", ".join(repr(n) for n in names) + "]")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- models


def emit_field(f: Field, prefix: str) -> list[str]:
    attr = py_attr(f.name, prefix)
    t = type_py(f.type)
    desc = f.description
    if f.unit:
        desc = (desc + f" Unit: {f.unit}.").strip()
    args = []
    optional = not f.required or f.type.nullable
    if optional and not f.type.nullable:
        t = f"{t} | None"
    if optional:
        args.append("None")
    if attr != f.name:
        args.append(f"alias={f.name!r}")
    if desc:
        args.append(f"description={desc!r}")
    return [f"    {attr}: {t} = PydField({', '.join(args)})" if args else f"    {attr}: {t}"]


def emit_models(api: Api, prefix: str) -> str:
    lines = [
        HEADER,
        '"""Typed rows returned by the API. Field names are the API\'s, so the docs read the same."""',
        "",
        "from __future__ import annotations",
        "",
        "from datetime import date, datetime",
        "from typing import Any, Literal",
        "",
        "from pydantic import Field as PydField",
        "",
        "from .._models_base import BytnodeModel",
        "",
        "",
    ]
    for m in api.models.values():
        lines.append(f"class {m.name}(BytnodeModel):")
        routes = [r.path for r in api.routes if r.model == m.name]
        head = f"Row of `{'`, `'.join(routes)}`." if routes else (m.description or f"Nested object ({m.name}).")
        lines.append(f'    """{esc(head)}"""')
        lines.append("")
        if not m.fields:
            lines.append("    pass")
        for f in m.fields:
            lines.extend(emit_field(f, prefix))
        lines.append("")
        lines.append("")
    lines.append("__all__ = [" + ", ".join(repr(m) for m in api.models) + "]")
    return "\n".join(lines) + "\n"


